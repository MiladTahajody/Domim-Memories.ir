// Keeps <title>, description, keywords, canonical, Open Graph and Twitter tags in the page language.
function setHead(t) {
  const set = (sel, attr, val) => { const el = document.querySelector(sel); if (el) el.setAttribute(attr, val); };
  const url = SITE.url + FILE[page] + (lang === 'en' ? '?lang=en' : '');
  document.title = t.titles[page];
  set('meta[name=description]', 'content', t.descriptions[page]);
  set('meta[name=keywords]', 'content', t.keywords[page]);
  set('link[rel=canonical]', 'href', url);
  set('meta[property="og:title"]', 'content', t.titles[page]);
  set('meta[property="og:description"]', 'content', t.descriptions[page]);
  set('meta[property="og:url"]', 'content', url);
  set('meta[property="og:locale"]', 'content', lang === 'fa' ? 'fa_IR' : 'en_US');
  set('meta[property="og:locale:alternate"]', 'content', lang === 'fa' ? 'en_US' : 'fa_IR');
  set('meta[property="og:image"]', 'content', SITE.url + SITE.ogImage);
  set('meta[name="twitter:title"]', 'content', t.titles[page]);
  set('meta[name="twitter:description"]', 'content', t.descriptions[page]);
  set('meta[name="twitter:image"]', 'content', SITE.url + SITE.ogImage);
  set('meta[name="apple-mobile-web-app-title"]', 'content', t.brand);

  // Structured data (JSON-LD): organisation, website, breadcrumbs, product categories, FAQ
  const base = SITE.url;
  const sameAs = Object.values(LINKS).filter(u => !/your_/.test(u));      // sample links are ignored
  const graph = [
    {'@type': 'Organization', '@id': base + '#org', name: t.brand, url: base, logo: base + 'icons/icon-512.svg', ...(sameAs.length ? {sameAs} : {})},
    {'@type': 'WebSite', '@id': base + '#site', url: base, name: t.brand, inLanguage: lang, publisher: {'@id': base + '#org'}},
    {'@type': 'BreadcrumbList', itemListElement: (page === 'home' ? [[t.nav.home, base]] : [[t.nav.home, base], [t.nav[page], base + FILE[page]]])
      .map(([name, item], i) => ({'@type': 'ListItem', position: i + 1, name, item}))}
  ];
  if (page === 'home') {
    graph.push({'@type': 'ItemList', name: t.productsTitle, itemListElement: Object.keys(PRODUCTS).map((k, i) => ({'@type': 'ListItem', position: i + 1, name: t.nav[k], url: base + FILE[k]}))});
    graph.push({'@type': 'FAQPage', mainEntity: t.faq.map(([q, a]) => ({'@type': 'Question', name: q, acceptedAnswer: {'@type': 'Answer', text: a}}))});
  } else {
    graph.push({'@type': 'CollectionPage', name: t.titles[page], description: t.descriptions[page], url: base + FILE[page], inLanguage: lang, isPartOf: {'@id': base + '#site'},
      mainEntity: {'@type': 'ItemList', itemListElement: allRows(page).map((r, i) => ({'@type': 'ListItem', position: i + 1, name: nameOf(r)}))}});
  }
  let ld = document.getElementById('ld-json');
  if (!ld) { ld = document.createElement('script'); ld.type = 'application/ld+json'; ld.id = 'ld-json'; document.head.appendChild(ld); }
  ld.textContent = JSON.stringify({'@context': 'https://schema.org', '@graph': graph});
}

/* ---- 6. Photo zoom (lightbox): close with X, Esc or a click outside the photo ---- */
function openBox(fig) {
  const img = fig.querySelector('img');
  const box = document.createElement('div');
  box.className = 'lb'; box.setAttribute('role', 'dialog'); box.setAttribute('aria-modal', 'true');
  box.innerHTML = `<button class="lb-x" type="button" aria-label="${TEXT[lang].close}"><svg viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path d="M6 6l12 12M18 6L6 18"/></svg></button>` +
    (img ? `<img class="lb-img" src="${img.src}" alt="${img.alt}">`
         : `<figure class="ph lb-ph" data-path="${fig.dataset.path}"></figure>`);   // placeholder zoom until the real photo exists
  const onKey = e => { if (e.key === 'Escape') close(); };
  const close = () => { box.remove(); document.body.style.overflow = ''; document.removeEventListener('keydown', onKey); fig.focus(); };
  box.onclick = e => { if (e.target === box || e.target.closest('.lb-x')) close(); };
  document.addEventListener('keydown', onKey);
  document.body.style.overflow = 'hidden';
  document.body.appendChild(box);
  box.querySelector('.lb-x').focus();
}

// Zoom binding for one photo frame (also used for the photo that a showcase selector swaps in)
function bindZoom(f) {
  f.tabIndex = 0; f.setAttribute('role', 'button');
  f.setAttribute('aria-label', (f.querySelector('img') || {}).alt || f.dataset.path);
  f.onclick = () => openBox(f);
  f.onkeydown = e => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); openBox(f); } };
}
// Narrow screens: scroll the option row (sideways only, the page itself does not move) so the chosen option is in the middle. Works for LTR and RTL.
function centerOption(seg, smooth) {
  const on = seg.querySelector('.seg-b.on'); if (!on || seg.scrollWidth <= seg.clientWidth) return;
  const b = on.getBoundingClientRect(), s = seg.getBoundingClientRect();
  seg.scrollBy({left: (b.left + b.width / 2) - (s.left + s.width / 2), behavior: smooth ? 'smooth' : 'auto'});
}
// Showcase selector: show the photo of the chosen option without rebuilding the page
function selectType(seg, id) {
  const sec = seg.closest('.tsec'), fig = sec.querySelector('.show'), g = PRODUCTS[page].groups.filter(x => x.display === 'showcase')[+fig.dataset.g];
  const row = g && g.items.find(r => r[0] === id); if (!row) return;
  typeId = id;
  seg.querySelectorAll('.seg-b').forEach(b => { const on = b.dataset.id === id; b.classList.toggle('on', on); b.setAttribute('aria-selected', on); });
  fig.innerHTML = ph(`${PRODUCTS[page].folder}/${id}/${filesOf(row, id)[0]}`, `${nameOf(row)} - ${TEXT[lang].nav[page]}`, 'eager') + `<figcaption>${nameOf(row)}</figcaption>`;
  bindZoom(fig.querySelector('.ph'));
  centerOption(seg, true);                                         // narrow screens: the options scroll sideways, keep the chosen one in view
}
window.addEventListener('hashchange', () => { const id = typeFromHash(); const seg = document.querySelector('.seg'); if (id && seg) { selectType(seg, id); seg.closest('.tsec').querySelector('.tsh').scrollIntoView({behavior: 'smooth'}); } });

