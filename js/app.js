/* ==========================================================
   Domim - app.js  (the ENGINE: you normally do NOT edit this file)
   Reads js/content.js + js/icons.js, builds header / page / footer, switches fa/en without reload,
   and keeps the search-engine tags (title, description, keywords, structured data) in sync.
   Load order on every page:  content.js -> icons.js -> fx.js -> scroll.js -> app.js
   fx.js (animations) is started from render() at the very end: FX.init()
   scroll.js (sideways scrolling of tag rows and the review gallery) is started from render(): Scroll.init()

   MAP OF THIS FILE
    1. State (language, current page, selected tag)
    2. Small building blocks (image placeholder, floating stars)
    3. Header and footer
    4. Pages: Home sections, product page
    5. Search-engine tags (meta + JSON-LD)
    6. Photo zoom (lightbox)
    7. Render everything + language switch
   ========================================================== */
