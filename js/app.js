// The menu opens above the button. If the button is too near the top of the screen (for example after scrolling down to the footer)
// the page scrolls up a little first, so the whole menu is visible below the sticky header.
const ensureRoom = ord => {
  const menu = ord.querySelector('.ord-menu'), hb = document.querySelector('.hbar');
  const need = (hb ? hb.getBoundingClientRect().bottom : 0) + menu.offsetHeight + 14 + 16;      // header + menu + gap + a little air
  const top = ord.getBoundingClientRect().top;
  if (top < need) window.scrollBy({top: top - need, behavior: window.matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth'});
};
function bindOrder(ord) {
  const btn = ord.querySelector('.ord-btn'), fx = ord.querySelector('.ord-fx');
  const burst = () => {                                           // 14 sparkles flying outwards from the button centre
    fx.innerHTML = Array.from({length: 14}, (_, i) => {
      const ang = (i / 14) * Math.PI * 2 + (i % 2 ? .2 : 0), dist = 70 + (i % 3) * 26;
      return `<i class="${i % 3 === 0 ? 'star' : ''}" style="--dx:${Math.round(Math.cos(ang) * dist)}px;--dy:${Math.round(Math.sin(ang) * dist)}px;--s:${6 + (i % 4) * 2}px;--c:${['var(--pc)', 'var(--p2)', '#ffd66b', '#fff'][i % 4]}"></i>`;
    }).join('');
    ord.classList.remove('fire'); void ord.offsetWidth; ord.classList.add('fire');   // restart the CSS animations
  };
  btn.onclick = () => {
    if (ord.classList.contains('open')) { closeOrder(ord); return; }
    ensureRoom(ord);                                                      // the menu always opens ABOVE the button: make room if the button is too high on the screen
    ord.classList.add('open'); btn.setAttribute('aria-expanded', 'true');
    burst();
  };
  ord.querySelectorAll('.ord-o').forEach(a => a.addEventListener('click', () => setTimeout(() => closeOrder(ord), 300)));
}

/* ---- 7. Render everything + language switch (no page reload) ---- */
// keepScroll = true when only the selected tag changed: tag rows keep their scroll position
function render(keepScroll = false) {
  const t = TEXT[lang], html = document.documentElement;
  const rowsX = keepScroll ? [...document.querySelectorAll('.tags')].map(e => e.scrollLeft) : [];
  const y = window.scrollY;                                         // the page keeps its vertical position on every re-render

  html.lang = lang; html.dir = lang === 'fa' ? 'rtl' : 'ltr';
  setHead(t);
  document.getElementById('site-header').innerHTML = header(t);
  document.getElementById('page').innerHTML = page === 'home' ? home(t) : product(t, page);
  document.getElementById('site-footer').innerHTML = footer(t);

  document.querySelector('.sw').onclick = () => {                  // language switch
    lang = lang === 'fa' ? 'en' : 'fa';
    try { localStorage.setItem('domim-lang', lang); } catch (e) {}
    if (new URLSearchParams(location.search).has('lang')) {         // keep ?lang= in the address bar in sync
      const u = new URL(location.href); u.searchParams.set('lang', lang); history.replaceState(null, '', u);
    }
    render(true);
  };
  document.querySelector('.logo').onclick = e => {                 // logo on Home = back to top; on other pages it opens Home
    if (page === 'home') { e.preventDefault(); window.scrollTo({top: 0}); }
  };
  document.querySelectorAll('.gal .ph, .show .ph, .rv .ph').forEach(bindZoom);   // gallery photos, the showcase photo and review screenshots open in the lightbox
  document.querySelectorAll('.seg').forEach(seg => seg.querySelectorAll('.seg-b').forEach(b => b.onclick = () => selectType(seg, b.dataset.id)));
  document.querySelectorAll('.ord').forEach(bindOrder);                                  // order button with the messenger menu
  document.querySelectorAll('.seg').forEach(seg => centerOption(seg, false));                // e.g. albums.html#framed: the row opens with that option in view
  document.querySelectorAll('.aq').forEach(b => b.onclick = () => {   // FAQ accordion
    const item = b.closest('.ai'), open = !item.classList.contains('open');
    item.classList.toggle('open', open); b.setAttribute('aria-expanded', open);
  });
  if (typeof Scroll !== 'undefined') Scroll.init(rowsX, t, num);   // tag rows + review gallery (js/scroll.js)

  if (y) { html.style.scrollBehavior = 'auto'; window.scrollTo(0, y); html.style.scrollBehavior = ''; }
  if (typeof FX !== 'undefined') FX.init();                        // start animations for the freshly built page
}
render();
