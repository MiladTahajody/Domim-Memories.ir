/* ==========================================================
   Domim - scroll.js  (sideways scrolling: you normally do NOT edit this file)
   Two things scroll sideways on this site and both live here:
    1. Tag rows on the product pages (.sc > .tags): arrows appear only while tags are clipped on that side;
       with a mouse the row can also be dragged (press on a tag and hold, then move) and glides a little after you let go.
    2. Review gallery on Home (.rv): arrows, drag with the mouse, a draggable position bar, one total count.
   app.js calls Scroll.init(rowsX, texts, num) after every render (language switch, tag change).
   Load order on every page:  content.js -> icons.js -> fx.js -> scroll.js -> app.js

   MAP OF THIS FILE
    1. Helpers (RTL-aware position, resize handling)
    2. Tag rows (arrows + mouse drag)
    2b. Showcase counter ("2 of 4" next to the Album Types title, only while its options scroll sideways)
    3. Review gallery (arrows, mouse drag, position bar, counter)
    4. Scroll.init
   ========================================================== */
'use strict';

const Scroll = (() => {
  /* ---- 1. Helpers ---- */
  // In RTL rows scrollLeft is 0 at the start and negative toward the end, so positions are read with Math.abs().
  const isRtl = el => getComputedStyle(el).direction === 'rtl';
  const clamp = (v, a, b) => Math.min(b, Math.max(a, v));
  let onResize = [];                                            // functions re-run when the window size changes
  window.addEventListener('resize', () => onResize.forEach(f => f()));
  window.addEventListener('hashchange', () => setTimeout(() => onResize.forEach(f => f()), 0));   // a link such as albums.html#framed changes the chosen option

  // Scroll a row just enough to reveal a clipped item
  const reveal = (box, item) => {
    if (!item) return;
    const a = item.getBoundingClientRect(), b = box.getBoundingClientRect();
    if (a.left < b.left) box.scrollLeft -= b.left - a.left + 8;
    else if (a.right > b.right) box.scrollLeft += a.right - b.right + 8;
  };

  /* ---- 2. Tag rows ---- */
  // Mouse drag for a scrolling row: press on it and move. Touch screens already scroll natively.
  // A drag never counts as a click (so the tag under the pointer is not opened); after a quick drag the row glides on a little.
  function dragScroll(el) {
    let down = false, dragging = false, sx = 0, s0 = 0, lx = 0, lt = 0, vel = 0, raf = 0;
    el.addEventListener('pointerdown', e => {
      if (e.pointerType !== 'mouse' || e.button !== 0) return;
      cancelAnimationFrame(raf);
      down = true; dragging = false; sx = lx = e.clientX; s0 = el.scrollLeft; lt = e.timeStamp; vel = 0;
    });
    el.addEventListener('pointermove', e => {
      if (!down) return;
      const dx = e.clientX - sx;
      if (!dragging && Math.abs(dx) > 5) { dragging = true; el.classList.add('drag'); el.setPointerCapture(e.pointerId); }   // up to 5px = a click, more = a drag
      if (!dragging) return;
      el.scrollLeft = s0 - dx;                                  // works for LTR and RTL rows alike
      const dt = e.timeStamp - lt;
      if (dt > 0) { vel = (e.clientX - lx) / dt; lx = e.clientX; lt = e.timeStamp; }   // px per ms
    });
    const end = () => {
      if (!down) return;
      down = false;
      if (!dragging) return;
      el.classList.remove('drag');
      let v = -vel * 16;                                        // px per frame, then it slows down
      const glide = () => { if (Math.abs(v) < .5) return; el.scrollLeft += v; v *= .94; raf = requestAnimationFrame(glide); };
      if (Math.abs(vel) > .2) glide();
      setTimeout(() => { dragging = false; }, 60);              // the click that follows a drag is swallowed first (below)
    };
    el.addEventListener('pointerup', end); el.addEventListener('pointercancel', end);
    el.addEventListener('click', e => { if (dragging) { e.stopPropagation(); e.preventDefault(); } }, true);
  }

  // rowsX = saved scroll positions, so rows do not jump when a tag is selected
  function tagRows(rowsX) {
    document.querySelectorAll('.sc').forEach((sc, i) => {
      const el = sc.querySelector('.tags'), left = sc.querySelector('.l'), right = sc.querySelector('.r');
      const fit = () => sc.classList.toggle('ov', el.scrollWidth > el.clientWidth + 1);   // arrows exist only if the row overflows
      const update = () => {
        const rtl = isRtl(el), max = el.scrollWidth - el.clientWidth, x = el.scrollLeft;
        left.classList.toggle('off', !(rtl ? -x < max - 1 : x > 1));
        right.classList.toggle('off', !(rtl ? x < -1 : x < max - 1));
      };
      fit();
      if (rowsX[i] !== undefined) el.scrollLeft = rowsX[i];
      reveal(el, el.querySelector('.on'));
      left.onclick = () => el.scrollBy({left: -el.clientWidth * .7, behavior: 'smooth'});
      right.onclick = () => el.scrollBy({left: el.clientWidth * .7, behavior: 'smooth'});
      el.addEventListener('scroll', update, {passive: true});
      dragScroll(el);
      onResize.push(() => { fit(); update(); });
      update();
    });
  }

  /* ---- 2b. Showcase counter ----
     When the options of a showcase (Album Types) do not all fit on screen (tablets / phones) they scroll sideways, so a small counter
     next to the title tells the visitor which option is chosen and how many there are in total. On the web everything is visible: no counter. */
  function showcases(t, num) {
    document.querySelectorAll('.tsec').forEach(sec => {
      const seg = sec.querySelector('.seg'), cnt = sec.querySelector('.cnt');
      if (!seg || !cnt) return;
      const update = () => {
        const bs = [...seg.querySelectorAll('.seg-b')], i = Math.max(0, bs.findIndex(b => b.classList.contains('on')));
        sec.classList.toggle('ov', seg.scrollWidth > seg.clientWidth + 1);            // counter exists only if the row scrolls
        cnt.textContent = (t.showCount || '{a}/{n}').replace(/\{(\w)\}/g, (_, k) => num({a: i + 1, n: bs.length}[k]));
      };
      seg.addEventListener('click', update);                                         // runs after app.js has marked the chosen option
      onResize.push(update);
      update();
    });
  }

  /* ---- 3. Review gallery ---- */
  function reviews(t, num) {
    const box = document.querySelector('.rv');
    if (!box) return;
    const el = box.querySelector('.rv-track'), left = box.querySelector('.rv-arr.l'), right = box.querySelector('.rv-arr.r');
    const count = box.querySelector('.rv-count'), bar = box.querySelector('.rv-bar'), thumb = bar.querySelector('b');
    const fill = (s, v) => s.replace(/\{(\w)\}/g, (_, k) => num(v[k]));
    // one screenshot's width + the gap = the distance between two snap points (offsetWidth ignores the entrance animation transform)
    const stepOf = () => (el.firstElementChild ? el.firstElementChild.offsetWidth : 1) + parseFloat(getComputedStyle(el).columnGap || 0);
    const maxOf = () => el.scrollWidth - el.clientWidth;

    // Arrows, counter, position bar: refreshed on every scroll
    const update = () => {
      const rtl = isRtl(el), max = maxOf(), x = Math.abs(el.scrollLeft), over = max > 1, step = stepOf();
      box.classList.toggle('ov', over);                                                  // arrows, hint and bar exist only if the row overflows
      left.classList.toggle('off', !(rtl ? x < max - 1 : x > 1));                        // RTL: the start of the row is on the right
      right.classList.toggle('off', !(rtl ? x > 1 : x < max - 1));
      const a = Math.min(REVIEW_COUNT, Math.round(x / step) + 1);
      const b = Math.min(REVIEW_COUNT, x >= max - 1 ? REVIEW_COUNT : a + Math.max(1, Math.floor((el.clientWidth + step * .1 + 4) / step)) - 1);
      count.textContent = fill(!over ? t.reviewsCount : a === b ? t.reviewsOne : t.reviewsRange, {a, b, n: REVIEW_COUNT});
      const w = over ? Math.max(12, el.clientWidth / el.scrollWidth * 100) : 100;
      thumb.style.width = w + '%'; thumb.style.insetInlineStart = (over ? x / max * (100 - w) : 0) + '%';
    };

    // Glide to the nearest screenshot (used after a drag, so the row never stops half-way between two screenshots).
    // flick: +1 = go on to the next one in the physical right direction, -1 = left, 0 = just the nearest
    const settle = flick => {
      const max = maxOf(), step = stepOf(), rtl = isRtl(el);
      let idx = el.scrollLeft / step;
      idx = flick > 0 ? Math.ceil(idx - .001) : flick < 0 ? Math.floor(idx + .001) : Math.round(idx);
      el.scrollTo({left: clamp(idx * step, rtl ? -max : 0, rtl ? 0 : max), behavior: 'smooth'});
    };

    // Arrows: one page (80% of the visible width) per click. -1 = physical left, +1 = physical right
    const go = dir => el.scrollBy({left: dir * el.clientWidth * .8, behavior: 'smooth'});
    left.onclick = () => go(-1); right.onclick = () => go(1);

    // Mouse: press on a screenshot and drag sideways (touch screens already scroll natively; a quick flick moves one more screenshot)
    let down = false, dragging = false, sx = 0, s0 = 0, lx = 0, lt = 0, t0 = 0, vel = 0;
    el.addEventListener('pointerdown', e => {
      if (e.pointerType !== 'mouse' || e.button !== 0) return;
      down = true; dragging = false; sx = lx = e.clientX; s0 = el.scrollLeft; lt = t0 = e.timeStamp; vel = 0;
    });
    el.addEventListener('pointermove', e => {
      if (!down) return;
      const dx = e.clientX - sx;
      if (!dragging && Math.abs(dx) > 5) { dragging = true; el.classList.add('drag'); el.setPointerCapture(e.pointerId); }   // up to 5px = a click, more = a drag
      if (!dragging) return;
      el.scrollLeft = s0 - dx;
      const dt = e.timeStamp - lt;
      if (dt > 0) { vel = (e.clientX - lx) / dt; lx = e.clientX; lt = e.timeStamp; }    // px per ms, for flick detection
    });
    const release = e => {
      if (!down) return;
      down = false;
      if (!dragging) return;
      el.classList.remove('drag');
      const dx = e.clientX - sx, quick = e.timeStamp - t0 < 350 && Math.abs(dx) > 30;       // a short, quick gesture = a flick
      settle(quick || Math.abs(vel) > .5 ? (dx < 0 ? 1 : -1) : 0);
    };
    el.addEventListener('pointerup', release); el.addEventListener('pointercancel', release);
    // A drag must not open the lightbox: swallow the click that follows it
    el.addEventListener('click', e => { if (dragging) { e.stopPropagation(); e.preventDefault(); dragging = false; } }, true);

    // Position bar: click anywhere on it to jump, or drag the thumb (mouse, finger or pen)
    let grab = 0, barDown = false;
    const fromBar = clientX => {
      const r = bar.getBoundingClientRect(), free = Math.max(1, r.width - thumb.offsetWidth);
      const p = clamp((clientX - r.left - grab) / free, 0, 1);                           // 0..1 measured from the physical left of the bar
      el.scrollLeft = (isRtl(el) ? -(1 - p) : p) * maxOf();
    };
    bar.addEventListener('pointerdown', e => {
      e.preventDefault(); barDown = true; bar.setPointerCapture(e.pointerId);
      bar.classList.add('drag'); el.classList.add('drag');
      const tr = thumb.getBoundingClientRect();
      grab = e.clientX >= tr.left && e.clientX <= tr.right ? e.clientX - tr.left : tr.width / 2;   // keep the grab point on the thumb, else centre it on the pointer
      fromBar(e.clientX);
    });
    bar.addEventListener('pointermove', e => { if (barDown) fromBar(e.clientX); });
    const barUp = () => { if (!barDown) return; barDown = false; bar.classList.remove('drag'); el.classList.remove('drag'); settle(0); };
    bar.addEventListener('pointerup', barUp); bar.addEventListener('pointercancel', barUp);

    el.addEventListener('scroll', update, {passive: true});
    onResize.push(update);
    update();
  }

  /* ---- 4. Scroll.init ---- */
  function init(rowsX = [], t = {}, num = String) {
    onResize = [];                                              // the page was rebuilt: forget the old rows
    tagRows(rowsX);
    showcases(t, num);
    reviews(t, num);
    if (document.fonts && document.fonts.ready) document.fonts.ready.then(() => onResize.forEach(f => f()));   // font widths decide whether a row scrolls
  }
  return {init};
})();
