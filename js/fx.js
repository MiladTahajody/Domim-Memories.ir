/* ==========================================================
   Domim - fx.js  (ANIMATION ENGINE: you normally do NOT edit this file)
   Works together with fx.css. It only toggles CSS classes / variables; all visuals are in fx.css.

   What it does
    - builds the floating clouds, balloons, stars, moons and hearts of the animated background (#bg) + scroll / mouse parallax
    - reveals sections when they scroll into view  ([data-rv] -> class "in")
    - category cards "lazy load": skeleton first, then the real card  (class "show" -> "loaded")
    - makes illustrations draw themselves (class "on" on .art)
    - 3D tilt that follows the mouse on [data-tilt] elements and on the hero
    - fills the "How to order" path while scrolling  ([data-flow], variable --p)
    - back-to-top button and a soft page-leave animation for browsers without view transitions
   Everything is skipped when the device asks for reduced motion: pages then simply show final states.
   app.js calls FX.init() after every render (language switch, tag change).
   ========================================================== */
'use strict';

const FX = (() => {
  const root = document.documentElement;
  const mq = q => !!(window.matchMedia && window.matchMedia(q).matches);
  const reduce = mq('(prefers-reduced-motion: reduce)');
  const fine = mq('(hover: hover) and (pointer: fine)');       // a real mouse (no tilt on touch screens)
  const hasIO = 'IntersectionObserver' in window;
  const on = !reduce;                                           // are effects enabled?
  if (on) root.classList.add('fx');

  const bg = document.getElementById('bg');
  const rnd = (i, k) => { const x = Math.sin(i * 91.7 + k * 17.3) * 43758.5453; return x - Math.floor(x); };

  /* ---- Background: floating clouds, balloons, stars, moons and hearts (motion + colours are in css/fx.css) ---- */
  if (bg) {
    const layer = bg.querySelector('.bgl-s');
    // 4-point sparkle and heart outlines on a 96 x 96 grid
    const sparkle = (x, y, s) => `M${x} ${y - s}C${x + s * .12} ${y - s * .3} ${x + s * .3} ${y - s * .12} ${x + s} ${y}C${x + s * .3} ${y + s * .12} ${x + s * .12} ${y + s * .3} ${x} ${y + s}C${x - s * .12} ${y + s * .3} ${x - s * .3} ${y + s * .12} ${x - s} ${y}C${x - s * .3} ${y - s * .12} ${x - s * .12} ${y - s * .3} ${x} ${y - s}z`;
    const hrt = (x, y, s) => `M${x} ${y + s * .9}C${x - s * 1.6} ${y - s * .1} ${x - s * .9} ${y - s * 1.1} ${x} ${y - s * .35}C${x + s * .9} ${y - s * 1.1} ${x + s * 1.6} ${y - s * .1} ${x} ${y + s * .9}z`;
    const SHAPE = {
      star: c => `<path class="bs-${c}" d="${sparkle(48, 48, 42)}"/>`,
      heart: c => `<path class="bs-${c}" d="${hrt(48, 48, 36)}"/>`,
      moon: c => `<path class="bs-${c}" d="M62 10A40 40 0 1 0 86 76A32 32 0 0 1 62 10Z"/>`,
      cloud: c => `<path class="bs-${c}" d="M26 70a18 18 0 0 1-2-35.9A24 24 0 0 1 70 30a20 20 0 0 1 4 40z"/>`,
      balloon: c => `<path class="bs-${c}" d="M48 8c15 0 26 12 26 27 0 17-14 31-26 37C36 66 22 52 22 35 22 20 33 8 48 8z"/><path class="bs-${c}" d="M43 74h10l-5 8z"/><path class="bs-str" d="M48 82c-6 5 6 7 0 12"/>`
    };
    const kinds = [['star', 'butter'], ['heart', 'blush'], ['moon', 'butter'], ['cloud', 'sky'], ['balloon', 'lilac'], ['star', 'peach'], ['heart', 'lilac'], ['balloon', 'mint']];
    if (layer) for (let i = 0; i < 16; i++) {
      const [k, c] = kinds[i % kinds.length], el = document.createElement('i');
      el.className = 'fy' + (on ? '' : ' still');                // with "reduce motion" the shapes stand still
      el.style.cssText = `left:${(rnd(i, 1) * 96).toFixed(1)}%;--y:${(rnd(i, 6) * 90).toFixed(0)}%;--s:${(28 + rnd(i, 2) * 32).toFixed(0)}px;--t:${(34 + rnd(i, 3) * 34).toFixed(0)}s;--d:${(-rnd(i, 4) * 60).toFixed(1)}s;--x:${(rnd(i, 5) * 60 - 30).toFixed(0)}px`;
      el.innerHTML = `<svg viewBox="0 0 96 96" aria-hidden="true" focusable="false">${SHAPE[k](c)}</svg>`;
      layer.appendChild(el);
    }
  }

  /* ---- Back-to-top button ---- */
  const totop = document.createElement('button');
  totop.type = 'button'; totop.className = 'totop'; totop.innerHTML = IC.up;
  totop.onclick = () => window.scrollTo({top: 0, behavior: 'smooth'});
  document.body.appendChild(totop);

  /* ---- Scroll + mouse loop (one requestAnimationFrame per change) ---- */
  let ticking = false, mx = 0, my = 0;
  const clamp = (v, a = 0, b = 1) => Math.min(b, Math.max(a, v));

  // "How to order": --p (0..1) grows while the section crosses the screen; nodes light up when the line reaches them
  function updateFlow(f) {
    const vertical = mq('(max-width: 800px)'), r = f.getBoundingClientRect(), vh = window.innerHeight;
    let p = 1;
    if (on) p = vertical ? clamp((vh * .66 - r.top - 40) / Math.max(1, r.height - 80)) : clamp((vh * .86 - r.top) / (vh * .42));
    f.style.setProperty('--p', p.toFixed(3));
    const items = [...f.querySelectorAll('.fs')], H = Math.max(1, r.height - 84);
    items.forEach((li, i) => li.classList.toggle('on', p > 0 && p >= (vertical ? li.offsetTop / H : i / (items.length - 1)) - .001));
  }
  function frame() {
    ticking = false;
    const y = window.scrollY || window.pageYOffset || 0;
    if (bg && on) { bg.style.setProperty('--sy', y); bg.style.setProperty('--mx', mx.toFixed(3)); bg.style.setProperty('--my', my.toFixed(3)); }
    totop.classList.toggle('show', y > 700);
    const hd = document.getElementById('site-header'); if (hd) hd.classList.toggle('stuck', y > 24);   // header gets compact after a little scrolling
    document.querySelectorAll('[data-flow]').forEach(updateFlow);
    const hv = document.querySelector('[data-hero]');            // the hero stage leans back a little while you scroll down
    if (hv && on) hv.style.setProperty('--hp', clamp(y / Math.max(1, hv.offsetHeight * 1.4)).toFixed(3));
  }
  const tick = () => { if (!ticking) { ticking = true; requestAnimationFrame(frame); } };
  window.addEventListener('scroll', tick, {passive: true});
  window.addEventListener('resize', tick);
  if (on && fine) window.addEventListener('pointermove', e => {
    if (e.pointerType === 'touch') return;
    mx = (e.clientX / window.innerWidth - .5) * 2; my = (e.clientY / window.innerHeight - .5) * 2; tick();
  }, {passive: true});

  /* ---- init(): called after every render ---- */
  let observers = [], timers = [], offs = [];
  function init() {
    observers.forEach(o => o.disconnect()); timers.forEach(clearTimeout); offs.forEach(f => f());
    observers = []; timers = []; offs = [];
    const after = (ms, fn) => timers.push(setTimeout(fn, ms));
    const watch = (els, opts, fn) => {                          // run fn(el) once when el becomes visible
      const o = new IntersectionObserver(es => es.forEach(e => { if (e.isIntersecting) { o.unobserve(e.target); fn(e.target); } }), opts);
      els.forEach(el => o.observe(el)); observers.push(o);
    };
    const animate = on && hasIO;
    totop.setAttribute('aria-label', (TEXT[root.lang] || TEXT.fa).toTop);

    // 1) scroll reveal
    const rv = [...document.querySelectorAll('[data-rv]')];
    if (animate) watch(rv, {threshold: .12, rootMargin: '0px 0px -6% 0px'}, el => el.classList.add('in'));
    else rv.forEach(el => el.classList.add('in'));

    // 2) category cards: skeleton -> loaded (phones: each card on its own when it appears)
    const finish = c => { c.classList.add('show', 'loaded'); const a = c.querySelector('.art'); if (a) a.classList.add('on'); };
    const cards = [...document.querySelectorAll('.pcard')];
    const play = (c, i) => {
      after(i * 170, () => c.classList.add('show'));
      after(i * 170 + 1050, () => { c.classList.add('loaded'); const a = c.querySelector('.art'); if (a) a.classList.add('on'); });
    };
    if (!animate) cards.forEach(finish);
    else if (mq('(max-width: 800px)')) watch(cards, {threshold: .25}, c => play(c, 0));
    else { const grid = document.querySelector('[data-cards]'); if (grid) watch([grid], {threshold: .3}, () => cards.forEach(play)); }

    // 3) illustrations draw themselves (cards do it above; the hero ones right after load)
    const arts = [...document.querySelectorAll('.art:not(.pc-art .art)')];
    if (animate) {
      watch(arts.filter(a => !a.closest('.hero')), {threshold: .25}, a => a.classList.add('on'));
      after(350, () => arts.filter(a => a.closest('.hero')).forEach(a => a.classList.add('on')));
    } else arts.forEach(a => a.classList.add('on'));

    // 4) 3D tilt that follows the mouse
    if (on && fine) {
      document.querySelectorAll('[data-tilt]').forEach(el => {
        const max = parseFloat(el.dataset.tilt) || 8;
        const move = e => {
          if (e.pointerType === 'touch') return;
          const r = el.getBoundingClientRect(), x = (e.clientX - r.left) / r.width, y = (e.clientY - r.top) / r.height;
          el.style.setProperty('--ry', ((x - .5) * 2 * max).toFixed(2) + 'deg');        // pointer on the right -> right side goes back
          el.style.setProperty('--rx', (-(y - .5) * 2 * max).toFixed(2) + 'deg');
          el.style.setProperty('--gx', (x * 100).toFixed(0) + '%'); el.style.setProperty('--gy', (y * 100).toFixed(0) + '%');
        };
        const leave = () => { el.style.setProperty('--rx', '0deg'); el.style.setProperty('--ry', '0deg'); };
        el.addEventListener('pointermove', move); el.addEventListener('pointerleave', leave);
      });
      const hero = document.querySelector('.hero'), hv = document.querySelector('[data-hero]');
      if (hero && hv) {                                          // the whole hero area steers the 3D stage
        const move = e => {
          if (e.pointerType === 'touch') return;
          const r = hero.getBoundingClientRect();
          hv.style.setProperty('--ry', (((e.clientX - r.left) / r.width - .5) * 16).toFixed(2) + 'deg');
          hv.style.setProperty('--rx', (-((e.clientY - r.top) / r.height - .5) * 12).toFixed(2) + 'deg');
        };
        hero.addEventListener('pointermove', move);
        hero.addEventListener('pointerleave', () => { hv.style.setProperty('--rx', '0deg'); hv.style.setProperty('--ry', '0deg'); });
      }
    }
    frame();
  }

  /* ---- Page-leave fade (only computers with a mouse, and only where the browser has no cross-document view transitions; touch devices just navigate) ---- */
  const hasVT = 'CSSViewTransitionRule' in window;
  document.addEventListener('click', e => {
    if (!on || hasVT || !window.matchMedia('(hover:hover) and (pointer:fine)').matches || e.defaultPrevented || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
    const a = e.target.closest && e.target.closest('a[href]');
    if (!a || a.target || a.hasAttribute('download')) return;
    const u = new URL(a.href, location.href);
    if (u.origin !== location.origin || u.pathname === location.pathname) return;       // only real page changes
    e.preventDefault(); root.classList.add('leaving');
    setTimeout(() => { location.href = a.href; }, 190);
  });
  window.addEventListener('pageshow', () => root.classList.remove('leaving'));          // coming back with the Back button

  return {init};
})();
